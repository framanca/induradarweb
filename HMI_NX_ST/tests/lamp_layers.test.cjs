test('lamp accepts an individual ON color without the old rays in ON or OFF',()=>{
 const off=C.statusSvg('lamp',false,'#ff3355'),on=C.statusSvg('lamp',true,'#ff3355');
 assert.match(off,/<circle/);assert.match(on,/<circle/);
 assert.match(off,/fill="#e2e8f0"/);
 assert.match(on,/fill="#ff3355"/);
 assert.equal((off.match(/<circle/g)||[]).length,1);
 assert.equal((on.match(/<circle/g)||[]).length,1);
 assert.doesNotMatch(on,/<path|<line|<polygon|<image/);
 assert.doesNotMatch(off,/<path|<line|<polygon|<image/);
 assert.equal(C.statusSvg('lamp',true,'#ff3355"><script>'),C.statusSvg('lamp',true),'invalid colors fall back safely');
 const motor=C.statusSvg('motor',true,'#ff3355');
 assert.match(motor,/#15803d/,'other industrial SVG symbols keep their previous state colors');
 assert.doesNotMatch(motor,/#ff3355/);
});
test('lamp color survives save/load and is exported for every runtime state update',()=>{
 const p=C.newProject();p.internalVariables=[{name:'Run_Local',type:'BOOL',value:true}];
 const o=C.newObject('status');o.binding='Run_Local';o.symbolType='lamp';o.lampOnColor='#ff5500';
 p.screens[0].objects.push(o);
 assert.deepEqual(Array.from(C.validate(p)),[]);
 const roundtrip=C.normalize(JSON.parse(JSON.stringify(p)));
 assert.equal(roundtrip.screens[0].objects[0].lampOnColor,'#ff5500');
 const html=C.buildRuntimeHTML(roundtrip);
 assert.match(html,/"lampOnColor":"#ff5500"/);
 assert.match(html,/statusSvg\(o\.symbolType\|\|"lamp",visualOn,o\.lampOnColor\)/);
 assert.match(html,/statusSvg\(type,false,o\.lampOnColor\)/);
 assert.doesNotMatch(html,/M50 5v9M50 62v10/);
 assert.doesNotMatch(html,/M17 38H7M93 38H83/);
 const legacy=C.copy(p);delete legacy.screens[0].objects[0].lampOnColor;
 assert.equal(C.normalize(legacy).screens[0].objects[0].lampOnColor,'#86efac');
 const bad=C.copy(p);bad.screens[0].objects[0].lampOnColor='" onerror=alert(1)';
 assert.equal(C.normalize(bad).screens[0].objects[0].lampOnColor,'#86efac');
 const script=html.match(/<script>([\s\S]*)<\/script>/)[1];
 assert.doesNotThrow(()=>new Function(script));
});
test('all widget types change front/back by array order and preserve order in export',()=>{
 const p=C.newProject();
 const screen=p.screens[0];
 const a=Object.assign(C.newObject('text'),{text:'Capa_A'});
 const b=Object.assign(C.newObject('shape'),{text:'Capa_B'});
 const c=Object.assign(C.newObject('text'),{text:'Capa_C'});
 screen.objects.push(a,b,c);
 const ids=()=>Array.from(screen.objects,x=>x.id).join(',');
 assert.equal(C.moveWidgetLayer(screen.objects,a.id,'front'),true);
 assert.equal(ids(),[b.id,c.id,a.id].join(','));
 assert.equal(C.moveWidgetLayer(screen.objects,a.id,'front'),false);
 assert.equal(C.moveWidgetLayer(screen.objects,a.id,'back'),true);
 assert.equal(ids(),[a.id,b.id,c.id].join(','));
 assert.equal(C.moveWidgetLayer(screen.objects,c.id,'back'),true);
 assert.equal(ids(),[c.id,a.id,b.id].join(','));
 assert.equal(C.moveWidgetLayer(screen.objects,'missing','front'),false);
 assert.equal(C.moveWidgetLayer(screen.objects,a.id,'invalid'),false);
 assert.deepEqual(Array.from(C.validate(p)),[]);
 const saved=C.normalize(JSON.parse(JSON.stringify(p)));
 assert.deepEqual(Array.from(saved.screens[0].objects,x=>x.id),[c.id,a.id,b.id]);
 const html=C.buildRuntimeHTML(saved);
 const pos=['Capa_C','Capa_A','Capa_B'].map(x=>html.indexOf('"text":"'+x+'"'));
 assert.ok(pos.every(n=>n>=0));
 assert.ok(pos[0]<pos[1]&&pos[1]<pos[2],'exported DOM follows array order, back to front');
 assert.match(html,/for\(const o of P\.screens\[screenIndex\]\.objects\)/);
});
test('base screen remains behind local screen; its own elements can be reordered',()=>{
 const p=C.newProject();
 p.baseScreen=C.newBaseScreen();
 const a=Object.assign(C.newObject('text'),{text:'Base_1'});
 const b=Object.assign(C.newObject('text'),{text:'Base_2'});
 p.baseScreen.objects.push(a,b);
 const o=Object.assign(C.newObject('text'),{text:'Own_1'});
 p.screens[0].objects.push(o);p.screens[0].useBase=true;
 assert.deepEqual(Array.from(C.screenObjects(p,p.screens[0]),x=>x.text),['Base_1','Base_2','Own_1']);
 assert.equal(C.moveWidgetLayer(p.baseScreen.objects,a.id,'front'),true);
 assert.deepEqual(Array.from(C.screenObjects(p,p.screens[0]),x=>x.text),['Base_2','Base_1','Own_1']);
 assert.equal(C.moveWidgetLayer(p.screens[0].objects,a.id,'front'),false);
 assert.deepEqual(Array.from(C.validate(p)),[]);
 const html=C.buildRuntimeHTML(p);
 const pos=['Base_2','Base_1','Own_1'].map(x=>html.indexOf('"text":"'+x+'"'));
 assert.ok(pos[0]<pos[1]&&pos[1]<pos[2]);
});
